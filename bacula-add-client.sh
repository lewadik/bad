#!/usr/bin/env bash
# bacula-add-client.sh
#
# Registers a client on the director and produces a one-file installer for it.
# This is the whole client onboarding workflow:
#
#   bacula-add-client.sh web01 10.0.0.21            # register + emit bundle
#   scp /etc/bacula/enroll/web01-install.sh root@10.0.0.21:/root/
#   ssh root@10.0.0.21 'bash /root/web01-install.sh'
#   bacula-add-client.sh web01 --test               # run a full job and wait
#
# Usage: bacula-add-client.sh NAME [ADDRESS] [options]
#
#   --address ADDR      address the director uses (default: NAME)
#   --os linux|windows  client operating system (default: linux)
#   --fileset NAME      reuse a shared FileSet (default: LinuxServer/WindowsServer)
#   --include PATH      add a path to a private FileSet for this client (repeatable)
#   --no-monthly        skip the monthly full job
#   --test              queue a full backup now and wait for the result
#   --push              scp+ssh the bundle to ADDRESS and run it immediately
#   --remove            unregister the client (catalog history is kept)
#   --list              list registered clients
#   --force             rewrite the config and rotate the password
#   --dry-run           show what would be written, change nothing
#   -h, --help          this text
#
# Exit codes: 0 ok, 1 usage/precondition, 2 registration failed, 4 test backup failed.

set -Eeuo pipefail

CONF_DIR=${CONF_DIR:-/etc/bacula}
CLIENTS_D=$CONF_DIR/clients.d
ENROLL_D=$CONF_DIR/enroll
SITE_FILE=${SITE_FILE:-$CONF_DIR/site.env}
BCONSOLE=${BCONSOLE:-/usr/bin/bconsole}
SELF_DIR=$(cd -- "$(dirname -- "$(readlink -f "$0" 2>/dev/null || echo "$0")")" && pwd)

log()  { printf '\n\033[1;36m==> %s\033[0m\n' "$*"; }
info() { printf '    %s\n' "$*"; }
warn() { printf '\033[1;33mWARNING: %s\033[0m\n' "$*" >&2; }
die()  { printf '\033[1;31mERROR: %s\033[0m\n' "$*" >&2; exit "${2:-1}"; }
have() { command -v "$1" >/dev/null 2>&1; }

usage() { sed -n '2,/^# Exit codes/p' "$0" | sed 's/^# \{0,1\}//'; exit 0; }

NAME=""
ADDRESS=""
CLIENT_OS="linux"
FILESET=""
INCLUDES=()
NO_MONTHLY=0
DO_TEST=0
DO_PUSH=0
DO_REMOVE=0
DO_LIST=0
FORCE=0
DRY_RUN=0

while (($#)); do
  case $1 in
    --address)    ADDRESS=${2:?}; shift 2 ;;
    --os)         CLIENT_OS=${2:?}; shift 2 ;;
    --fileset)    FILESET=${2:?}; shift 2 ;;
    --include)
      IFS=',' read -r -a __parts <<<"${2:?}"
      INCLUDES+=("${__parts[@]}")
      shift 2 ;;
    --no-monthly) NO_MONTHLY=1; shift ;;
    --test)       DO_TEST=1; shift ;;
    --push)       DO_PUSH=1; shift ;;
    --remove)     DO_REMOVE=1; shift ;;
    --list)       DO_LIST=1; shift ;;
    --force)      FORCE=1; shift ;;
    --dry-run)    DRY_RUN=1; shift ;;
    -h|--help)    usage ;;
    -*)           die "unknown option: $1 (try --help)" ;;
    *)
      if [[ -z $NAME ]]; then NAME=$1
      elif [[ -z $ADDRESS ]]; then ADDRESS=$1
      else die "unexpected argument: $1"
      fi
      shift ;;
  esac
done

[[ ${EUID:-$(id -u)} -eq 0 ]] || { if (( ! DRY_RUN )); then die "run as root"; fi; }
[[ -f $SITE_FILE ]] || die "$SITE_FILE missing — is this a Bacula server built by deploy-bacula-server.sh?"
# shellcheck disable=SC1090
. "$SITE_FILE"

if (( DO_LIST )); then
  printf 'Registered clients (%s):\n' "$CLIENTS_D"
  if compgen -G "$CLIENTS_D/*.conf" >/dev/null; then
    for f in "$CLIENTS_D"/*.conf; do
      n=$(basename "$f" .conf)
      a=$(sed -n 's/^[[:space:]]*Address = "\(.*\)"$/\1/p' "$f" | head -1)
      printf '  %-24s %s\n' "$n" "${a:-?}"
    done
  else
    printf '  (none)\n'
  fi
  exit 0
fi

[[ -n $NAME ]] || die "client name required (try --help)"
[[ $NAME =~ ^[a-z0-9][a-z0-9-]{0,31}$ ]] || die "invalid name: lowercase letters, digits and dashes, max 32"
case $CLIENT_OS in linux|windows) ;; *) die "--os must be linux or windows" ;; esac
[[ -n $ADDRESS ]] || ADDRESS=$NAME
[[ $ADDRESS =~ ^[A-Za-z0-9._:-]+$ ]] || die "invalid address: $ADDRESS"

CLIENT_CONF="$CLIENTS_D/$NAME.conf"
pc() { sudo -u bacula psql -qtAX -d "$DB_NAME" -c "$1"; }

reload_director() {
  if (( DRY_RUN )); then info "[dry-run] reload director"; return 0; fi
  if ! out=$(printf 'reload\nquit\n' | "$BCONSOLE" -c "$CONF_DIR/bconsole.conf" -n 2>&1); then
    printf '%s\n' "$out" >&2
    die "director reload failed" 2
  fi
  sleep 1
  systemctl is-active --quiet bacula-director 2>/dev/null || die "director is not running after reload" 2
  info "director reloaded"
}

# clients.conf is generated from the directory, so add/remove never has to edit
# the director config in place.
render_clients_conf() {
  local tmp; tmp=$(mktemp)
  {
    printf '# Generated by bacula-add-client.sh — one include per client.\n'
    printf '# Do not edit: run bacula-add-client.sh (or --remove) instead.\n'
    if compgen -G "$CLIENTS_D/*.conf" >/dev/null; then
      for f in "$CLIENTS_D"/*.conf; do
        printf '@%s\n' "$f"
      done
    fi
  } >"$tmp"
  if (( DRY_RUN )); then
    info "[dry-run] clients.conf:"; sed 's/^/      /' "$tmp"
  else
    install -m 0640 -o root -g bacula "$tmp" "$CONF_DIR/clients.conf"
  fi
  rm -f "$tmp"
}

validate_director_config() {
  if (( DRY_RUN )); then info "[dry-run] would run bacula-dir -t"; return 0; fi
  local out
  if ! out=$(sudo -u bacula /usr/sbin/bacula-dir -t -c "$CONF_DIR/bacula-dir.conf" 2>&1); then
    printf '%s\n' "$out" >&2
    return 1
  fi
  return 0
}

# ----------------------------------------------------------------------------
# --remove
# ----------------------------------------------------------------------------
if (( DO_REMOVE )); then
  [[ -f $CLIENT_CONF ]] || die "no such client: $NAME"
  log "Unregistering $NAME"
  rm -f "$CLIENT_CONF"
  render_clients_conf
  if validate_director_config; then
    reload_director
    info "jobs <name>-daily / <name>-monthly are gone from the director config"
  else
    die "config invalid after removal — restore $CLIENT_CONF from /etc/bacula/backup-*" 2
  fi
  warn "catalog history is kept on purpose (restores of old jobs still work)."
  warn "To purge it: bconsole -> purge jobs client=$NAME (destructive, irreversible)."
  exit 0
fi

# ----------------------------------------------------------------------------
# register
# ----------------------------------------------------------------------------
FILESET_NAME=${FILESET:-$([[ $CLIENT_OS == windows ]] && echo WindowsServer || echo LinuxServer)}
CUSTOM_FS=0
if ((${#INCLUDES[@]})); then
  FILESET_NAME="$NAME-fs"
  CUSTOM_FS=1
fi

PASSWORD=""
if [[ -f $CLIENT_CONF && $FORCE -eq 0 ]]; then
  PASSWORD=$(sed -n 's/^[[:space:]]*Password = "\(.*\)"$/\1/p' "$CLIENT_CONF" | head -1)
  info "client already registered — keeping the existing password (use --force to rotate)"
fi
[[ -n $PASSWORD ]] || PASSWORD=$(openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | cut -c1-32)

CLIENT_CONF_OUT=$CLIENT_CONF
if (( DRY_RUN )); then
  CLIENT_CONF_OUT=$(mktemp)
fi

[[ $CLIENT_OS == windows ]] && JOBDEF_DAILY=WindowsClient || JOBDEF_DAILY=LinuxClient
[[ $CLIENT_OS == windows ]] && JOBDEF_MONTHLY=WindowsClientMonthly || JOBDEF_MONTHLY=LinuxClientMonthly

log "Writing $CLIENT_CONF"

{
  printf '#\n# Client: %s (%s) — generated by bacula-add-client.sh on %s\n#\n\n' \
    "$NAME" "$CLIENT_OS" "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  cat <<EOF
Client {
  Name = "$NAME"
  Address = "$ADDRESS"
  FDPort = 9102
  Catalog = "MyCatalog"
  Password = "$PASSWORD"
  File Retention = 60 days
  Job Retention = 6 months
  AutoPrune = yes
  Maximum Concurrent Jobs = 2
}

EOF
  if (( CUSTOM_FS )); then
    printf 'FileSet {\n  Name = "%s"\n  Include {\n    Options { Signature = SHA256 }\n' "$FILESET_NAME"
    for p in "${INCLUDES[@]}"; do printf '    File = "%s"\n' "$p"; done
    printf '  }\n  Exclude {\n    File = "/proc"\n    File = "/sys"\n    File = "/dev"\n'
    printf '    File = "/run"\n    File = "/tmp"\n    File = "/var/tmp"\n    File = "/var/cache"\n  }\n}\n\n'
  fi
  cat <<EOF
Job {
  Name = "$NAME-daily"
  JobDefs = "$JOBDEF_DAILY"
  Client = "$NAME"
EOF
  if (( CUSTOM_FS )); then printf '  FileSet = "%s"\n' "$FILESET_NAME"; fi
  printf '}\n\n'
  if (( ! NO_MONTHLY )); then
    cat <<EOF
Job {
  Name = "$NAME-monthly"
  JobDefs = "$JOBDEF_MONTHLY"
  Client = "$NAME"
EOF
    if (( CUSTOM_FS )); then printf '  FileSet = "%s"\n' "$FILESET_NAME"; fi
    printf '}\n'
  fi
} >"$CLIENT_CONF_OUT"

if (( DRY_RUN )); then
  info "[dry-run] $CLIENT_CONF would be:"
  sed 's/^/      /' "$CLIENT_CONF_OUT"
  rm -f "$CLIENT_CONF_OUT"
  render_clients_conf
  printf '\nClient %s, fileset %s, jobs %s-daily%s\n' "$NAME" "$FILESET_NAME" "$NAME" \
    "$([[ $NO_MONTHLY == 0 ]] && printf ', %s-monthly' "$NAME")"
  exit 0
fi

chown root:bacula "$CLIENT_CONF"
chmod 0640 "$CLIENT_CONF"
info "wrote $CLIENT_CONF (jobs $NAME-daily$([[ $NO_MONTHLY == 0 ]] && echo ", $NAME-monthly"))"

render_clients_conf
if ! validate_director_config; then
  mv "$CLIENT_CONF" "$CLIENT_CONF.broken"
  render_clients_conf
  die "director rejected the new client config — kept as $CLIENT_CONF.broken, nothing reloaded" 2
fi
reload_director

# ----------------------------------------------------------------------------
# bundle
# ----------------------------------------------------------------------------
BUNDLE=""
if (( ! DRY_RUN )); then
  install -d -m 0700 -o root -g root "$ENROLL_D"
fi

if [[ $CLIENT_OS == linux ]]; then
  SRC=""
  for cand in /usr/local/sbin/bacula-client-install.sh \
              "$(cd -- "$(dirname -- "$0")" && pwd)/bacula-client-install.sh"; do
    if [[ -f $cand ]]; then SRC=$cand; break; fi
  done
  [[ -n $SRC ]] || die "bacula-client-install.sh not found (expected in /usr/local/sbin or next to this script)"
  BUNDLE="$ENROLL_D/$NAME-install.sh"
  {
    printf '#!/usr/bin/env bash\n'
    printf '# Bacula File Daemon bundle for %s — generated %s\n' "$NAME" "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    printf '# Contains the file daemon password. Delete it after use: shred -u "$0"\n\n'
    printf 'CLIENT_NAME=%q\n' "$NAME"
    printf 'DIRECTOR_NAME=%q\n' "$DIR_NAME"
    printf 'DIRECTOR_ADDR=%q\n' "$DIR_ADDR"
    printf 'FD_PASSWORD=%q\n' "$PASSWORD"
    printf 'CLIENT_OS=%q\n' "$CLIENT_OS"
    sed -n '/^# ==== BODY ====$/,$p' "$SRC"
  } >"$BUNDLE"
  chmod 0700 "$BUNDLE"
  chown root:root "$BUNDLE"
  # A bundle that does not parse is worse than no bundle: fail loudly here.
  if ! bash -n "$BUNDLE" 2>/dev/null || ! grep -q 'set -Eeuo pipefail' "$BUNDLE"; then
    rm -f "$BUNDLE"
    die "bundle assembly failed — bacula-client-install.sh has no BODY marker?" 2
  fi
  info "bundle: $BUNDLE"
else
  PS1_SRC=""
  for cand in /usr/local/sbin/bacula-client-install.ps1 "$SELF_DIR/bacula-client-install.ps1"; do
    if [[ -f $cand ]]; then PS1_SRC=$cand; break; fi
  done
  [[ -n $PS1_SRC ]] || die "bacula-client-install.ps1 not found (expected in /usr/local/sbin or next to this script)"
  install -m 0644 -o root -g root "$PS1_SRC" "$ENROLL_D/bacula-client-install.ps1"
  BUNDLE="$ENROLL_D/$NAME-install.ps1"
  cat >"$BUNDLE" <<EOF
# Bacula Windows client bootstrap for $NAME - generated $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Elevated PowerShell, with bacula-client-install.ps1 in the same folder:
#   powershell -ExecutionPolicy Bypass -File $NAME-install.ps1 -InstallerPath C:\\Temp\\bacula-win64.exe
\$ErrorActionPreference = 'Stop'
& "\$PSScriptRoot/bacula-client-install.ps1" -ClientName '$NAME' -DirectorName '$DIR_NAME' -DirectorAddress '$DIR_ADDR' -Password '$PASSWORD' @args
EOF
  chmod 0644 "$BUNDLE"
  info "bundle: $BUNDLE (+ bacula-client-install.ps1)"
fi

# ----------------------------------------------------------------------------
# optional push
# ----------------------------------------------------------------------------
if (( DO_PUSH )) && [[ -n $BUNDLE ]]; then
  log "Pushing the bundle to $ADDRESS"
  if ! scp -o BatchMode=yes -o ConnectTimeout=10 "$BUNDLE" "root@$ADDRESS:/root/"; then
    warn "scp failed — copy the bundle manually and run it on the client"
  else
    ssh -o BatchMode=yes -o ConnectTimeout=10 "root@$ADDRESS" \
      "bash /root/$(basename "$BUNDLE") && shred -u /root/$(basename "$BUNDLE")" ||
      warn "remote install failed — check the output above"
  fi
fi

# ----------------------------------------------------------------------------
# optional test backup
# ----------------------------------------------------------------------------
if (( DO_TEST )); then
  log "Running a full test backup of $NAME"
  [[ -n $BUNDLE ]] || die "--test needs a completed registration"
  out=$(printf 'run job="%s-daily" level=Full yes\nquit\n' "$NAME" |
        "$BCONSOLE" -c "$CONF_DIR/bconsole.conf" -n 2>&1) || true
  jobid=$(printf '%s\n' "$out" | sed -n 's/.*JobId[ =:]\+\([0-9]\+\).*/\1/p' | head -1)
  if [[ -z $jobid ]]; then
    printf '%s\n' "$out" | sed 's/^/      /' >&2
    die "the director did not queue the job — is the file daemon installed and reachable?" 4
  fi
  info "queued JobId=$jobid — waiting (max 30 min)"

  deadline=$(( SECONDS + 1800 ))
  status=""
  while (( SECONDS < deadline )); do
    status=$(pc "SELECT btrim(JobStatus) FROM Job WHERE JobId=$jobid" 2>/dev/null || true)
    case $status in
      T|W) break ;;
      E|e|f|A|D) break ;;
    esac
    sleep 5
  done

  IFS='|' read -r files bytes ela <<<"$(pc "SELECT JobFiles, JobBytes,
    COALESCE(extract(epoch from (EndTime-StartTime))::int,0) FROM Job WHERE JobId=$jobid" 2>/dev/null || echo '0|0|0')"
  case $status in
    T|W)
      info "job $status: ${files:-0} files, $(( ${bytes:-0} / 1048576 )) MiB, ${ela:-0}s"
      ;;
    E|e|f)
      printf '\n  last messages:\n'
      printf 'messages jobid=%s\nquit\n' "$jobid" | "$BCONSOLE" -c "$CONF_DIR/bconsole.conf" -n 2>&1 | tail -30 | sed 's/^/      /'
      die "test backup failed (JobStatus=$status)" 4
      ;;
    *)
      die "timed out waiting for JobId=$jobid (last status: ${status:-unknown})" 4
      ;;
  esac
fi

# ----------------------------------------------------------------------------
# hand-over
# ----------------------------------------------------------------------------
if [[ $CLIENT_OS == linux ]]; then
  cat <<EOF

$(printf '\033[1;32mClient %s registered\033[0m' "$NAME")

  address     $ADDRESS:9102
  fileset     $FILESET_NAME
  jobs        $NAME-daily$([[ $NO_MONTHLY == 0 ]] && printf ', %s-monthly' "$NAME-monthly")

Install the file daemon on the client (run this on the backup server; it needs
root SSH access to the client):

  scp $BUNDLE root@$ADDRESS:/root/
  ssh root@$ADDRESS 'bash /root/$(basename "$BUNDLE")'

Or let this script do it:

  bacula-add-client $NAME --push

Then verify end to end:

  bacula-add-client $NAME --test

The bundle is a credential. It is removed automatically by --push; otherwise
delete it after use:  shred -u $BUNDLE
EOF
else
  cat <<EOF

$(printf '\033[1;32mClient %s registered (Windows)\033[0m' "$NAME")

  address     $ADDRESS:9102
  fileset     $FILESET_NAME
  jobs        $NAME-daily$([[ $NO_MONTHLY == 0 ]] && printf ', %s-monthly' "$NAME-monthly")

Windows has no package-manager shortcut: copy the two files to the host and run
the wrapper in an elevated PowerShell. The wrapper carries this client's name,
director and password.

  1. copy  bacula-client-install.ps1  and  $NAME-install.ps1  to C:\\Temp
  2. download the Bacula Win64 installer (bacula-<version>-win64.exe) from
     https://www.bacula.org/  to the same directory
  3. powershell -ExecutionPolicy Bypass -File C:\\Temp\\$NAME-install.ps1 ^
        -InstallerPath C:\\Temp\\bacula-*-win64.exe

See deployment-scenario.md, "Windows clients", for the checks that follow.
EOF
fi
