<#
.SYNOPSIS
    Installs and enrols a Bacula Community File Daemon on Windows.

.DESCRIPTION
    Installs the Bacula Win64 file daemon (if not already present), writes
    bacula-fd.conf with this client's name/director/password, restarts the
    service and opens the file daemon port for the director only.

    Run from an elevated PowerShell. bacula-add-client.sh generates a wrapper
    (<client>-install.ps1) that fills in the first four parameters, so on the
    client you normally run:

        powershell -ExecutionPolicy Bypass -File C:\Temp\web01-install.ps1 `
                   -InstallerPath C:\Temp\bacula-15.0.3-win64.exe

.PARAMETER ClientName
    FileDaemon name; must equal the Client resource on the director.

.PARAMETER DirectorName
    Director resource name (bacula01-dir).

.PARAMETER DirectorAddress
    Director hostname or IP. Used for the firewall rule.

.PARAMETER Password
    Password from the Client resource. Generated by bacula-add-client.sh.

.PARAMETER InstallerPath
    Local path to bacula-<version>-win64.exe (or .msi). Not needed if Bacula is
    already installed.

.PARAMETER InstallerUrl
    Instead of InstallerPath: an https URL to download the installer from.
    Use only with a source you trust; verify the hash.

.PARAMETER Port
    File daemon port. Default 9102.

.PARAMETER SkipFirewall
    Do not create the inbound firewall rule.

.EXAMPLE
    .\bacula-client-install.ps1 -ClientName fs01 -DirectorName bacula01-dir `
        -DirectorAddress bacula01.example.com -Password 'SECRET' `
        -InstallerPath C:\Temp\bacula-15.0.3-win64.exe

.NOTES
    Exit codes: 0 ok, 1 precondition, 2 install failed, 3 service failed.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][ValidatePattern('^[a-z0-9][a-z0-9.-]{0,62}$')][string]$ClientName,
    [Parameter(Mandatory = $true)][string]$DirectorName,
    [Parameter(Mandatory = $true)][string]$DirectorAddress,
    [Parameter(Mandatory = $true)][string]$Password,
    [string]$InstallerPath,
    [string]$InstallerUrl,
    [int]$Port = 9102,
    [switch]$SkipFirewall,
    [switch]$Force
)

$ErrorActionPreference = 'Stop'

function Write-Step($msg) { Write-Host "`n==> $msg" -ForegroundColor Cyan }
function Write-Info($msg) { Write-Host "    $msg" }
function Fail($msg, $code) { Write-Host "ERROR: $msg" -ForegroundColor Red; exit $code }

# --- preconditions ----------------------------------------------------------
$principal = New-Object Security.Principal.WindowsPrincipal(
    [Security.Principal.WindowsIdentity]::GetCurrent())
if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    Fail "run this from an elevated PowerShell (Run as Administrator)" 1
}
if ([string]::IsNullOrWhiteSpace($Password)) { Fail "Password is empty" 1 }

$BaculaHome = Join-Path $env:ProgramFiles 'Bacula'
$ConfPath = Join-Path $BaculaHome 'bacula-fd.conf'
$WorkDir = Join-Path $BaculaHome 'working'

Write-Step "Preflight"
Write-Info "client    $ClientName"
Write-Info "director  $DirectorName at $DirectorAddress"
Write-Info "port      $Port"

$service = Get-Service -Name 'bacula-fd' -ErrorAction SilentlyContinue
if (-not $service) {
    $service = Get-Service | Where-Object { $_.Name -like '*bacula*' } | Select-Object -First 1
}

# --- install ----------------------------------------------------------------
Write-Step "File daemon"
if ($service) {
    Write-Info "already installed: $($service.Name) ($($service.Status))"
}
else {
    if (-not $InstallerPath -and $InstallerUrl) {
        $InstallerPath = Join-Path $env:TEMP (Split-Path $InstallerUrl -Leaf)
        Write-Info "downloading $InstallerUrl"
        try {
            [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
            Invoke-WebRequest -Uri $InstallerUrl -OutFile $InstallerPath -UseBasicParsing
        }
        catch { Fail "download failed: $($_.Exception.Message)" 2 }
    }
    if (-not $InstallerPath) {
        Fail "Bacula is not installed. Pass -InstallerPath with the Win64 installer from https://www.bacula.org/" 2
    }
    if (-not (Test-Path $InstallerPath)) { Fail "installer not found: $InstallerPath" 2 }

    $hash = (Get-FileHash $InstallerPath -Algorithm SHA256).Hash
    Write-Info "installer sha256 $hash"

    Write-Info "installing silently (this takes a minute)"
    if ($InstallerPath -like '*.msi') {
        $p = Start-Process msiexec.exe -ArgumentList "/i `"$InstallerPath`" /qn /norestart" -Wait -PassThru
    }
    else {
        $p = Start-Process -FilePath $InstallerPath -ArgumentList '/S' -Wait -PassThru
    }
    if ($p.ExitCode -ne 0) { Fail "installer exited with $($p.ExitCode)" 2 }

    Start-Sleep -Seconds 5
    $service = Get-Service -Name 'bacula-fd' -ErrorAction SilentlyContinue
    if (-not $service) { $service = Get-Service | Where-Object { $_.Name -like '*bacula*' } | Select-Object -First 1 }
    if (-not $service) { Fail "the installer finished but no Bacula service exists" 2 }
    Write-Info "installed: $($service.Name)"
}

# --- configuration ----------------------------------------------------------
Write-Step "Writing $ConfPath"
New-Item -ItemType Directory -Force -Path $WorkDir | Out-Null

if ((Test-Path $ConfPath) -and -not $Force) {
    $backup = "$ConfPath.orig"
    if (-not (Test-Path $backup)) {
        Copy-Item $ConfPath $backup
        Write-Info "kept the original config as $backup"
    }
}

$config = @"
#
# Bacula File Daemon - written by bacula-client-install.ps1 on $(Get-Date -Format 'yyyy-MM-ddTHH:mm:ssZ')
# Client resource on the director: $ClientName
#
FileDaemon {
  Name = $ClientName
  FDport = $Port
  WorkingDirectory = "C:/Program Files/Bacula/working"
  PidDirectory = "C:/Program Files/Bacula/working"
  Maximum Concurrent Jobs = 2
}

Director {
  Name = $DirectorName
  Password = "$Password"
}

Messages {
  Name = "Standard"
  director = $DirectorName = all, !skipped, !restored
}
"@

# No BOM and CRLF: the Windows file daemon is happier with plain ASCII.
[IO.File]::WriteAllText($ConfPath, ($config -replace "`r?`n", "`r`n"), (New-Object Text.ASCIIEncoding))
Write-Info "wrote $ConfPath"

# --- service ----------------------------------------------------------------
Write-Step "Restarting the service"
try {
    Set-Service -Name $service.Name -StartupType Automatic
    Restart-Service -Name $service.Name -Force
    Start-Sleep -Seconds 2
    $svc = Get-Service -Name $service.Name
    if ($svc.Status -ne 'Running') { Fail "service $($svc.Name) is $($svc.Status)" 3 }
    Write-Info "$($svc.Name): Running"
}
catch { Fail "could not restart $($service.Name): $($_.Exception.Message)" 3 }

# --- firewall ---------------------------------------------------------------
if (-not $SkipFirewall) {
    Write-Step "Firewall"
    $remote = @()
    try {
        $remote = [Net.Dns]::GetHostAddresses($DirectorAddress) |
            Where-Object { $_.AddressFamily -eq 'InterNetwork' } |
            ForEach-Object { $_.IPAddressToString }
    }
    catch { Write-Info "could not resolve $DirectorAddress; using it verbatim" }

    if (-not $remote) { $remote = @($DirectorAddress) }
    $ruleName = "Bacula File Daemon ($Port)"
    Get-NetFirewallRule -DisplayName $ruleName -ErrorAction SilentlyContinue | Remove-NetFirewallRule
    New-NetFirewallRule -DisplayName $ruleName -Direction Inbound -Action Allow `
        -Protocol TCP -LocalPort $Port -RemoteAddress $remote | Out-Null
    Write-Info "allowed $($remote -join ', ') -> $Port/tcp"
}

# --- verify -----------------------------------------------------------------
Write-Step "Result"
$listening = Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue
if ($listening) { Write-Info "listening on $Port/tcp" }
else { Write-Info "WARNING: nothing listening on $Port yet - check Event Viewer" }

Write-Host "`nFile daemon ready on $env:COMPUTERNAME" -ForegroundColor Green
Write-Host @"

  name        $ClientName
  director    $DirectorName at $DirectorAddress
  config      $ConfPath
  service     Get-Service $($service.Name)
  logs        Event Viewer -> Applications and Services -> Bacula

Next: on the director, run a first backup and wait for the result:

  bacula-add-client $ClientName --test
"@
exit 0
